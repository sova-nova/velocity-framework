"""Generate a subject's tutor workspace: the directory Claude Code runs in as the tutor.

Regenerated from the template on every launch. Notes protection, in layers:
1. The workspace (outside the vault) is the only working directory, and writes outside working
   directories are blocked.
2. Deny rules: no Edit or Read anywhere in the vault (notes come only through velocity's tools,
   which honour `private: true`), and no Bash.
3. A PreToolUse hook (`velocity hook guard`) refuses file edits that point into the vault.
4. Since 2026-11-12, the tutor has no file or command tools at all (TUTOR_TOOLS); layers 1-3
   stay, in case a Claude Code update or a changed launch brings them back.
Session logs are written by velocity's hooks and MCP server, which run outside Claude Code's
permission system, so the tutor itself never needs write access to the vault.
"""

import json
import shlex
import shutil
from importlib.resources import files
from pathlib import Path

from velocity.config import Config, Subject, data_dir
from velocity.runtime import self_command

MCP_SERVER_NAME = "velocity"

# The tutor may search the web and read Wikipedia (any language) without asking (decided
# 2026-11-12, security review L4): for recent topics, or facts it isn't sure of. Any
# other site is asked for in the terminal and impossible on the web page (nothing can
# answer there), because a fetched address can carry what the learner said anywhere.
# Subagents get the same rules (checked live).
# Claude Code's built-in tools the tutor gets at all (2026-11-12, after the security
# review): skills, loading tools on demand (velocity's own come from its MCP server and
# aren't affected), and the web lookups. No files, commands, helper agents, scheduled or
# remote jobs, notifications or messages to other sessions: the tutor uses none of them,
# and they were only denied or asked for before, not absent. Checked live.
TUTOR_TOOLS = ["Skill", "ToolSearch", "WebSearch", "WebFetch"]

ALLOWED_TOOLS = [
    f"mcp__{MCP_SERVER_NAME}",
    "WebSearch",
    "WebFetch(domain:*.wikipedia.org)",
]
GENERATED_NOTE = "Generated by velocity on every launch; edits are overwritten."


def workspace_dir(subject: Subject) -> Path:
    return data_dir() / "workspaces" / subject.slug


def permission_path(path: Path) -> str:
    """An absolute path as Claude Code's permission rules write it: POSIX form, and on
    Windows the drive as a folder (C:\\Users\\me -> /c/Users/me). With the rule's leading
    "/", that gives "//c/Users/me/**", an absolute path."""
    posix = path.as_posix()
    if path.drive and posix[1:2] == ":":
        return "/" + posix[0].lower() + posix[2:]
    return posix


def _hook_command(event: str, subject: Subject) -> str:
    return shlex.join(self_command("hook", event, "--subject", subject.slug))


def build_settings(config: Config, subject: Subject) -> dict:
    vault = permission_path(config.vault_path)

    def hook(event: str, timeout: int, matcher: str | None = None) -> dict:
        entry: dict = {
            "hooks": [
                {
                    "type": "command",
                    "command": _hook_command(event, subject),
                    "timeout": timeout,
                }
            ]
        }
        if matcher:
            entry["matcher"] = matcher
        return entry

    return {
        "_comment": GENERATED_NOTE,
        "permissions": {
            # Absolute paths need a leading "//" in permission rules.
            # velocity's own tools never write notes, so they don't need a prompt each time;
            # and the web lookups above.
            "allow": ALLOWED_TOOLS,
            "deny": [f"Edit(/{vault}/**)", f"Read(/{vault}/**)", "Bash"],
            "blockWritesOutsideWorkingDirectories": True,
        },
        "claudeMdExcludes": [(Path.home() / ".claude" / "CLAUDE.md").as_posix()],
        "hooks": {
            "SessionStart": [hook("session-start", 30)],
            "UserPromptSubmit": [hook("user-prompt", 10)],
            "Stop": [hook("stop", 30)],
            "SessionEnd": [hook("session-end", 10)],
            "PreToolUse": [
                hook("guard", 10, matcher="Edit|Write|MultiEdit|NotebookEdit")
            ],
            "PostToolUse": [
                hook("tool-use", 10, matcher=f"mcp__{MCP_SERVER_NAME}__.*|Skill")
            ],
        },
    }


def build_mcp_config(subject: Subject) -> dict:
    command, *args = self_command("mcp", "--subject", subject.slug)
    return {"mcpServers": {MCP_SERVER_NAME: {"command": command, "args": args}}}


def render_claude_md(subject: Subject, web: bool = False) -> str:
    """The tutor prompt. `web`: the engine can look things up (Claude Code: WebSearch and
    Wikipedia, ALLOWED_TOOLS), so the prompt says when and how (template/web.md)."""
    template = (
        files("velocity").joinpath("template/CLAUDE.md").read_text(encoding="utf-8")
    )
    if subject.sources:
        names = ", ".join(s.name for s in subject.sources)
        sources_section = (
            f"This subject has sources: {names}. Ground explanations in them: find where a "
            "topic is covered with `search_source` (or `get_outline`), read it with "
            "`read_section`, and cite sections as `<source> §<id>` (e.g. "
            f"`{subject.sources[0].name} §2.4`). Say so when an answer goes beyond the sources. "
            "For PDFs, `view_page` shows pages as printed, in a fraction of a second: use "
            "it for a specific page, for figures and diagrams (which `read_section` "
            "doesn't include), and to check formulas in text you read. `read_section`'s "
            "first read of a section can take a minute or two (OCR)."
        )
    else:
        sources_section = "This subject has no sources. Teach from general knowledge (and say so once, at the start)."
    persona = subject.persona.strip()
    persona_section = (
        f"\n## Extra instructions for this subject\n\n{persona}\n" if persona else ""
    )
    return template.format(
        subject_name=subject.name,
        subject_slug=subject.slug,
        subject_toml=(subject.dir / "subject.toml").as_posix(),
        sources_section=sources_section,
        persona_section=persona_section,
        web_section=(
            files("velocity").joinpath("template/web.md").read_text(encoding="utf-8")
            if web
            else ""
        ),
    )


def build_workspace(config: Config, subject: Subject) -> Path:
    """(Re)generate the workspace for a subject and return its path."""
    ws = workspace_dir(subject)
    if ws.exists():
        shutil.rmtree(ws)
    (ws / ".claude").mkdir(parents=True)

    (ws / "CLAUDE.md").write_text(render_claude_md(subject, web=True), encoding="utf-8")
    (ws / ".mcp.json").write_text(
        json.dumps(build_mcp_config(subject), indent=2), encoding="utf-8"
    )
    (ws / ".claude/settings.json").write_text(
        json.dumps(build_settings(config, subject), indent=2), encoding="utf-8"
    )
    # Local settings so the project MCP server is approved without a prompt.
    (ws / ".claude/settings.local.json").write_text(
        json.dumps({"enabledMcpjsonServers": [MCP_SERVER_NAME]}, indent=2),
        encoding="utf-8",
    )
    skills = files("velocity").joinpath("template/skills")
    for skill in skills.iterdir() if skills.is_dir() else []:
        if skill.is_dir():
            shutil.copytree(Path(str(skill)), ws / ".claude/skills" / skill.name)
    return ws


def claude_args(workspace: Path, resume: bool = False) -> list[str]:
    """Arguments for launching Claude Code as the tutor in a workspace.

    - Only project and local settings: the user's own Claude Code settings stay out.
    - Only velocity's MCP server: account connectors (e.g. claude.ai integrations) stay out.
    - velocity's tools are pre-approved on the command line, because project allow rules
      only apply after the workspace is trusted. Deny rules apply regardless.
    - Only the built-in tools the tutor uses (TUTOR_TOOLS); the others don't exist in its
      session at all.
    """
    args = [
        "--setting-sources",
        "project,local",
        "--strict-mcp-config",
        "--mcp-config",
        (workspace / ".mcp.json").as_posix(),
        "--tools",
        ",".join(TUTOR_TOOLS),
        "--allowedTools",
        *ALLOWED_TOOLS,
    ]
    if resume:
        args.append("--continue")
    return args
